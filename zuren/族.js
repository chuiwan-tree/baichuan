// 数字藏起来：堤和水只说成话。族里有人会看水色，说得准一点；没人会，只能猜。
function 看水(g) {
  const 懂 = 能干的(g).concat(g.人们.filter(p => p.活 && p.岁 >= 60)).filter(p => p.本事.includes('懂水')).sort((a, b) => b.岁 - a.岁)[0];
  const 粮 = g.粮 < 1 ? '缸底见了' : g.粮 < 3 ? '紧巴巴' : g.粮 < 6 ? '够吃' : '仓里有余';
  const n = 离大水(g);
  let 堤 = g.堤 < 3 ? '矮' : g.堤 < 6 ? '半人高' : g.堤 < 9 ? '齐胸' : '高过人头';
  let 水 = n === null ? '' : n === 0 ? '这一回有大水' : n === 1 ? '下一回有大水' : `再过 ${n} 回有大水`;
  if (n !== null && n <= 1) {
    const 力 = 大水力(g) - (g.渠通 ? 4 * Math.max(0, 1 - (g.淤 || 0) / 4) : 0);
    // 不添人，堤自己会塌一点；要补的按一个人一点五算，折成"堤上得有几个人"
    const 缺 = n === 0 ? (力 - g.堤 * 0.85) / 0.6 : (力 - g.堤 * 0.7225) / (0.6 * 1.85);
    const 真 = Math.max(0, Math.ceil(缺 / 1.5));
    if (懂) {
      // 年轻的看不准：偏多少看岁数，同一代同一个人看几遍都一样
      const h = Math.abs(Math.sin((g.底 || 1) * 0.0137 + g.代 * 12.9898 + 懂.id * 78.233)) * 43758.5453 % 1;
      let 说 = Math.max(0, 真 + Math.round((h - 0.5) * (懂.岁 < 35 ? 4.4 : 懂.岁 < 50 ? 1.8 : 0.6)));
      if (懂.看怕) 说 += 1;
      const 能 = 能干的(g).length;
      const 话 = 说 === 0 ? '不添人也顶得住' : `${n === 0 ? '这回' : '这两回'}堤上得有${数(说)}个人` + (说 > 能 ? '，咱们凑不齐' : '');
      if (n === 0) g.看过 = { 代: g.代, 谁: 懂.id, 说, 真, 话 };
      水 += `。${懂.名}看了水色，说：「${话}。」`;
    } else 水 += '。族里没人会看水色，堤够不够，谁也说不上来';
  }
  return { 粮, 堤, 水 };
}

