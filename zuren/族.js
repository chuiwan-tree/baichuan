function 卡(g, p) {
  const 线 = p.线.filter(l => 事类.has(l.类) || (l.类 === '子' && !人(g, l.谁).活)).slice(-2).map(l => 说线(g, p, l, true));
  const c = 师承(g, p); if (c && c[1] >= 3) 线.unshift(`${c[0].名}一门第${c[1]}代`);
  if (p.岁 >= 50) 线.unshift('这是能下地的最后十年');
  let 想 = p.想要 ? p.想要.话 : '';
  if (p.想要 && p.想要.处 === '堤' && 离大水(g) !== null && 离大水(g) <= 1 && 要去的(g).includes(p.id)) 想 = `「${离大水(g) === 0 ? '这回' : '下回'}让我去。」`;
  return { id: p.id, 名: p.名, 岁: p.岁, 本事: p.本事.join('、'), 一行: p.一行, 线, 想 };
}

