  for (const p of g.人们) if (p.活 && p.岁 >= 60 && p.想要) { if (p.想要.处 === '堤' || p.想要.话.includes('没守住')) { const 次 = p.想要.次 || 0;
      书.push({ 文: 次 === 0 ? `${p.名}老了，一辈子没轮上站到堤上去。` : `${p.名}在堤上守了${次 === 1 ? '一个' : 次 === 2 ? '两个' : '好几个'}十年，一回大水也没碰上。`, 重: 6 }); } p.没成 = p.想要.话; p.想要 = null; }
  for (const p of g.人们) if (p.活 && p.岁 >= 60 && !p.老过) { p.老过 = true; if (p.线.some(l => 事类.has(l.类))) 书.push({ 文: 句(g, R, p, '老', ''), 重: 4 }); }
