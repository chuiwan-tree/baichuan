  for (const k of ['堤', '渠', '田']) {
    const 老 = 在(k).filter(p => p.本事.includes('懂水')).sort((a, b) => b.岁 - a.岁)[0];
    if (!老) continue;
    const 徒数 = 老.线.filter(l => l.类 === '徒').length; if (徒数 >= 2) continue;
    for (const p of 在(k)) if (p !== 老 && 老.岁 - p.岁 >= 10 && !p.线.some(l => l.类 === '师') && !p.本事.includes('懂水')) {
      const 犟 = p.一行.includes('犟');
      if (犟 || R() < 0.35) { 翻.push(犟 ? `${老.名}想教${p.名}看水，${p.名}${'脾气犟，'}不肯学。` : `${p.名}跟${老.名}在${地名[k]}干了十年，没学进去。`); break; }
      p.线.push({ 类: '师', 谁: 老.id, 地: 地名[k] }); 老.线.push({ 类: '徒', 谁: p.id, 地: 地名[k] });
      p.本事.push('懂水');
      翻.push(`${p.名}跟${老.名}在${地名[k]}一起干了十年，${R() < 0.6 ? '学会了看水色' : `${老.名}教${他(p)}打桩，${p.名}嫌${他(老)}啰嗦，到底学会了`}。`);
      break;
    }
  }
  // 堤、渠
  const 愿 = (p, k) => p.想要 && p.想要.处 === k ? 1 : 0;
  const 堤力 = 在('堤').reduce((s, p) => s + (p.本事.includes('力气') ? 2 : 1) + (p.本事.includes('懂水') ? 0.5 : 0) + 愿(p, '堤'), 0);
  g.堤 = g.堤 * 0.85 + 堤力 * 0.6;
  const 渠力 = 在('渠').reduce((s, p) => s + (p.本事.includes('懂水') ? 2 : 1) + (p.本事.includes('手巧') ? 0.5 : 0) + 愿(p, '渠'), 0) * 0.5;
  g.淤 = g.淤 || 0;
  if (g.渠通) { g.淤 = Math.max(0, g.淤 + 1.2 - 渠力); if (g.淤 >= 4 && !g.淤死) { g.淤死 = true; 书.push({ 文: `北渠淤死了。${g.渠名 || '北渠'}底下长了芦苇，孩子们在里头捉蛙。`, 重: 6 }); } if (g.淤死 && g.淤 < 2) { g.淤死 = false; 书.push({ 文: `北渠又疏通了。`, 重: 5 }); } }
  if (!g.渠通) { g.渠 += 渠力; if (g.渠 >= 10) { g.渠通 = true; const 头 = 在('渠')[0]; 书.push({ 文: `北渠挖通了。${头 ? 头.名 + '在渠口站了一下午，' : ''}水第一回往北走。`, 重: 8 }); g.渠名 = 头 ? `${头.名}渠` : '北渠'; } }
