    书.push({ 文: 句(g, R, p, '死', 地名[p.在]), 重: 9 });
    for (const q of g.人们) if (q.活 && q.线.some(l => l.谁 === p.id)) { q.线.push({ 类: '失', 谁: p.id, 地: 地名[p.在] });
      if (p.在 === '堤' && q.线.some(l => l.谁 === p.id && l.类 === '子')) 给想要(R, q, '堤', `想守住${p.名}没守住的那段堤`); }
