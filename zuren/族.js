function 一根线(g, R, p, 地) {
  const 重 = { 失: 7, 救: 6, 欠: 6, 师: 5, 徒: 4, 子: 2 };
  const ls = p.线.filter(l => {
    if (l.类 === '生') return false;
    if (l.类 === '子' && 人(g, l.谁).活) return false;
    if (l.上回 === g.代 - 1) return false;                    // 上一代刚说过，隔开
    if (l.代 === g.代) return false;                          // 这一回刚生的线，这一回不当旧事说
    if (l.类 === '失' && (!p.活 || 人(g, l.谁).死于 === g.代)) return false;
    if (l.类 === '子' && 地 !== '') return false;
    return (l.用过 || 0) < 2;
  }).map((l, i) => ({ l, w: (重[l.类] || 1) + i * 0.3 + (l.地 === 地 ? 2 : 0) }));
  if (!ls.length) return null;
  ls.sort((a, b) => b.w - a.w);
  const l = (R() < 0.75 ? ls[0] : 挑(R, ls)).l;
  l.用过 = (l.用过 || 0) + 1; l.上回 = g.代;
  return l;
}
function 说线(g, p, l, 卡上) {
  const q = 人(g, l.谁), n = q.名;
  const T = 他(p);
  const 选 = a => 卡上 ? a[0] : a[Math.floor(Math.random() * a.length)];
  switch (l.类) {
    case '师': return 选([`跟${n}学过看水`, `${n}教${T}打的第一根桩还在堤脚下`, `${T}的桩是${n}手把手教的`]);
    case '徒': return 选([`带过${n}`, `${T}手把手教过${n}`]);
    case '欠': return 选([`欠${n}一条命`, `那年是${n}把${T}从水里拖上来的`]);
    case '救': return 选([`从水里拖上来过${n}`, `${n}那条命是${T}捞回来的`]);
    case '子': return 卡上 ? `${n}的孩子` : 选([`${T}是${n}的孩子`, `${n}走后，${T}成了家里顶梁的`]);
    case '失': { const 前 = l.地 === '家里' ? [`${T}常去${n}坟上坐坐`, `${n}留下的那把锄头${T}一直用着`] : l.地 === '荒年' ? [`${n}是荒年饿走的`] : [`${n}是那年大水没在${l.地}的`];
      return 选([...前, `自打${n}走了，${T}就不大说话`]); }
  }
  return '';
}
