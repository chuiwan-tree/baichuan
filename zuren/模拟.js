// 拿程序当玩家跑很多局，数撞（两个人指向同一样东西，或一个人往两头扯）、只一个人想的心事（单）、刺这些。node 模拟.js [局数]
// 撞的先后顺序有多少种：node 量撞.js [族.js] [局数]
const Z = require('./族.js');
const N = +(process.argv[2] || 300);
const 计 = { 局: 0, 撞: 0, 空: 0, 活到底: 0, 撞数分布: {}, 类: {}, 选: {}, 炸: 0, 化: 0, 碰: 0, 没说话: 0, 到老没说: 0, 偷看水: 0, 偷搭棚: 0, 冒头歪: 0 };
for (let s = 1; s <= N; s++) {
  const g = Z.新局(s * 7 + 3); let R = s * 9301 % 233280;
  const r = () => (R = (R * 9301 + 49297) % 233280) / 233280;
  for (let i = 0; i < 15 && !g.完; i++) {
    const n = Z.离大水(g); const 派 = {};
    for (const p of Z.能干的(g)) { Z.卡(g, p); const x = r();
      派[p.id] = n !== null && n <= 1 ? (x < 0.5 ? '堤' : x < 0.75 ? '田' : x < 0.9 ? '坡' : '渠') : (x < 0.45 ? '田' : x < 0.65 ? '堤' : x < 0.85 ? '渠' : '坡'); }
    const 结 = Z.过一代(g, 派);
    for (const t of 结.翻) { if (/各垒各的|谁也不让|挖歪了|没碰过面/.test(t)) 计.碰++; if (/少干了一截|少照看了|吵了一架/.test(t)) 计.冒头歪++; if (/偷看.+搭起了棚/.test(t)) 计.偷搭棚++; }
    if (Z.看水(g).水.includes('偷看')) 计.偷看水++;
  }
  计.局++; if (g.代 > 15) 计.活到底++;
  const zs = (g.撞们 || []).filter(z => z.定); const 成 = zs.filter(z => !z.空 && z.撞); 计.单 = (计.单 || 0) + zs.filter(z => !z.空 && !z.撞).length;
  计.撞数分布[(g.代 > 15 ? '到底' : '半路') + 成.length] = (计.撞数分布[(g.代 > 15 ? '到底' : '半路') + 成.length] || 0) + 1; 计.撞 += 成.length; 计.空 += zs.filter(z => z.空).length;
  for (const z of 成) { 计.类[z.类] = (计.类[z.类] || 0) + 1; const k = z.类 + ':' + z.选; 计.选[k] = (计.选[k] || 0) + 1; }
  const 谱 = g.族谱.flatMap(d => d.句).join('\n');
  计.炸 += (谱.match(/那晚.+就在/g) || []).length;
  计.化 += (谱.match(/扛了一宿的土|分了一块饼|互相送一碗年糕/g) || []).length;
  计.没说话 += (谱.match(/到死没跟|到死也没进过|家没人来/g) || []).length;
  计.到老没说 += ((g.终 || '').match(/到老没跟/g) || []).length;
}
console.log(计);
